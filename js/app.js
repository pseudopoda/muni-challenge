  function stats(items) {
    const done = items.filter((i) => i.done);
    const times = done.map((i) => state.done[i.id]).sort((a, b) => a - b);
    const miles = done.reduce((m, i) => m + pathLength(i.path), 0) / 1609.34;
    return {
      done: done.length,
      total: items.length,
      first: times[0],
      last: times[times.length - 1],
      elapsedMin: times.length > 1 ? (times[times.length - 1] - times[0]) / 60000 : 0,
      miles,
    };
  }

