  /** Draw a summary image (stats plus the day's route) and share or download it. */
  async function shareSummary(items, s) {
    const W = 1080, H = 1350, c = document.createElement("canvas");
    c.width = W; c.height = H;
    const g = c.getContext("2d");
    g.fillStyle = "#14161c"; g.fillRect(0, 0, W, H);

    // Route drawing, fitted into the lower part of the card.
    const pts = items.flatMap((i) => i.path || []).concat(trail);
    if (pts.length) {
      const lats = pts.map((p) => p[0]), lons = pts.map((p) => p[1]);
      const minLat = Math.min(...lats), maxLat = Math.max(...lats), minLon = Math.min(...lons), maxLon = Math.max(...lons);
      const kx = Math.cos(((minLat + maxLat) / 2) * Math.PI / 180);
      const box = { x: 90, y: 470, w: W - 180, h: H - 600 };
      const sc = Math.min(box.w / ((maxLon - minLon) * kx || 1), box.h / ((maxLat - minLat) || 1));
      const ox = box.x + (box.w - (maxLon - minLon) * kx * sc) / 2, oy = box.y + (box.h - (maxLat - minLat) * sc) / 2;
      const P = (p) => [ox + (p[1] - minLon) * kx * sc, oy + (maxLat - p[0]) * sc];
      g.lineCap = g.lineJoin = "round";
      if (trail.length > 1) { // where you actually went
        g.strokeStyle = "rgba(90,169,230,.55)";
        g.lineWidth = 4;
        g.beginPath();
        trail.forEach((p, k) => { const [x, y] = P(p); k && meters(trail[k - 1], p) < 1000 ? g.lineTo(x, y) : g.moveTo(x, y); });
        g.stroke();
      }
      for (const pass of [false, true]) {
        for (const it of items) {
          if (!it.path || it.done !== pass) continue;
          g.strokeStyle = pass ? it.color : "rgba(255,255,255,.18)";
          g.lineWidth = pass ? 9 : 5;
          g.beginPath();
          it.path.forEach((p, k) => { const [x, y] = P(p); k ? g.lineTo(x, y) : g.moveTo(x, y); });
          g.stroke();
        }
      }
    }

    g.fillStyle = "#fff";
    g.font = "700 64px Georgia, serif";
    g.fillText("The Muni Challenge", 90, 150);
    g.font = "800 150px system-ui, sans-serif";
    g.fillText(s.done + " / " + s.total, 90, 320);
    g.font = "500 40px system-ui, sans-serif";
    g.fillStyle = "rgba(255,255,255,.75)";
    const line2 = [s.miles.toFixed(1) + " mi on Muni", s.elapsedMin >= 1 ? duration(s.elapsedMin) : null, s.first ? "started " + clockOf(s.first) : null].filter(Boolean).join("  ·  ");
    g.fillText("lines ridden", 90, 380);
    g.fillText(line2, 90, 435);
    g.font = "400 30px system-ui, sans-serif";
    g.fillStyle = "rgba(255,255,255,.5)";
    g.fillText(new Date(s.last || Date.now()).toLocaleDateString(undefined, { weekday: "long", month: "long", day: "numeric", year: "numeric" }), 90, H - 60);

    const blob = await new Promise((r) => c.toBlob(r, "image/png"));
    const file = new File([blob], "muni-challenge.png", { type: "image/png" });
    const text = "Muni Challenge: " + s.done + "/" + s.total + " lines, " + s.miles.toFixed(1) + " mi" + (s.elapsedMin >= 1 ? " in " + duration(s.elapsedMin) : "") + ".";
    try {
      if (navigator.canShare && navigator.canShare({ files: [file] })) {
        await navigator.share({ files: [file], text });
        return;
      }
    } catch (e) {
      if (e && e.name === "AbortError") return; // user closed the share sheet
    }
    const a = el("a", { href: URL.createObjectURL(blob), download: "muni-challenge.png" });
    document.body.append(a);
    a.click();
    a.remove();
    setTimeout(() => URL.revokeObjectURL(a.href), 5000);
  }

