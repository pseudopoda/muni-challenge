(function () {
  "use strict";

  const DATA = window.MUNI_DATA; // which lines, notes, options (hand-written)
  const PLAN = window.MUNI_PLAN; // order, real stops, times, paths (generated by scripts/plan.py)
  const MAP = window.MuniMap;
  const WALK_MAX_M = PLAN.walkLimitM || 450; // ≈ 5 blocks, straight line
  const STORAGE_KEY = "muni-challenge:v1";
  const MODE_LABEL = { cable: "Cable car", rail: "Rail", bus: "Bus", owl: "Owl" };
  const WIDE = window.matchMedia("(min-width: 1000px)");
  const META = Object.fromEntries(DATA.lines.map((l) => [l.line, l]));

  // ---- State -------------------------------------------------------------

  function loadState() {
    const fallback = { options: { owl: false, event: false, earlybird: false }, done: {} };
    try {
      const raw = localStorage.getItem(STORAGE_KEY);
      if (!raw) return fallback;
      const parsed = JSON.parse(raw);
      return {
        options: Object.assign({}, fallback.options, parsed.options),
        done: parsed.done || {},
      };
    } catch (e) {
      return fallback;
    }
  }

  function saveState() {
    try {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(state));
    } catch (e) {
      /* storage unavailable (private mode etc.) — progress just won't persist */
    }
  }

  const state = loadState();

  // A leg's id is derived from its line name so saved progress survives re-planning.
  const legId = (leg) => leg.line.toLowerCase().replace(/[^a-z0-9]+/g, "-");

  function isOptionOn(key) {
    if (!key) return true;
    const opt = DATA.options[key];
    if (opt && opt.requires && !state.options[opt.requires]) return false;
    return !!state.options[key];
  }

  function meters(p, q) {
    const lat = ((p[0] + q[0]) / 2) * Math.PI / 180;
    const dx = (q[1] - p[1]) * 111320 * Math.cos(lat);
    const dy = (q[0] - p[0]) * 110540;
    return Math.round(Math.hypot(dx, dy));
  }

  /** Planned blocks for the current options, with line metadata merged in. */
  function visibleBlocks() {
    const blocks = PLAN.blocks
      .filter((b) => isOptionOn(b.option))
      .map((b) => ({
        ...b,
        legs: b.legs
          .map((l) => ({ ...META[l.line], ...l, option: l.option || (META[l.line] || {}).option }))
          .filter((l) => isOptionOn(l.option === "owl" ? null : l.option)),
      }))
      .filter((b) => b.legs.length);

    // Lines that aren't in SFMTA's schedule data (78X): slot in after the nearest planned leg.
    for (const [line, geo] of Object.entries(DATA.manual || {})) {
      const meta = META[line];
      if (!meta || !isOptionOn(meta.option)) continue;
      let best = null;
      blocks.forEach((b, bi) => b.legs.forEach((l, li) => {
        const d = meters(l.alight.ll, geo.board.ll);
        if (!best || d < best.d) best = { d, bi, li };
      }));
      if (best) {
        blocks[best.bi].legs.splice(best.li + 1, 0, { ...meta, ...geo, manual: true, path: [geo.board.ll, geo.alight.ll] });
      }
    }
    return blocks;
  }

  function toggleDone(id, value) {
    const on = value === undefined ? !state.done[id] : value;
    if (on) state.done[id] = Date.now();
    else delete state.done[id];
    saveState();
    render();
  }

  // ---- View (list / map) -------------------------------------------------

  function setView(view) {
    document.body.dataset.view = view;
    document.querySelectorAll(".view-toggle button").forEach((b) => {
      b.setAttribute("aria-selected", String(b.dataset.view === view));
    });
    if (view === "map") MAP.resize();
  }

  function showOnMap(id) {
    if (!WIDE.matches) setView("map");
    // Wait a frame so the map has its real size before zooming.
    requestAnimationFrame(() => { MAP.resize(); MAP.focus(id); });
  }

  // ---- Rendering ---------------------------------------------------------

  const $ = (id) => document.getElementById(id);

  function el(tag, attrs, children) {
    const node = document.createElement(tag);
    for (const [k, v] of Object.entries(attrs || {})) {
      if (v == null || v === false) continue;
      if (k === "class") node.className = v;
      else if (k === "text") node.textContent = v;
      else if (k.startsWith("on")) node.addEventListener(k.slice(2), v);
      else node.setAttribute(k, v === true ? "" : v);
    }
    for (const c of [].concat(children || [])) {
      if (c != null) node.append(c);
    }
    return node;
  }

  function renderOptions() {
    const box = $("options");
    box.replaceChildren();
    for (const [key, opt] of Object.entries(DATA.options)) {
      const disabled = opt.requires && !state.options[opt.requires];
      const input = el("input", {
        type: "checkbox",
        checked: !!state.options[key] && !disabled,
        disabled: disabled,
        onchange: (e) => {
          state.options[key] = e.target.checked;
          saveState();
          render();
        },
      });
      box.append(
        el("label", { class: "opt" + (disabled ? " disabled" : "") }, [
          input,
          el("span", { text: opt.label }),
          el("span", { class: "hint", text: opt.hint }),
        ])
      );
    }
  }

  function stopNode(stop) {
    const kids = [stop.name];
    if (stop.code) {
      kids.push(" ", el("a", { href: "https://www.sfmta.com/" + encodeURIComponent(stop.code), target: "_blank", rel: "noopener", class: "stop-link", text: "#" + stop.code + " live ↗" }));
    }
    return el("dd", {}, kids);
  }

  function walkText(m) {
    if (m == null) return null;
    if (m < 30) return "Same stop";
    return "Walk ~" + m + " m (≈" + Math.max(1, Math.round(m / 60)) + " min)";
  }

  function renderLeg(item) {
    const { leg, id, n } = item;
    const done = !!state.done[id];
    const classes = ["leg", leg.mode === "owl" && "owl", leg.risk && "risk", done && "done"].filter(Boolean).join(" ");

    const tags = [el("span", { class: "tag " + leg.mode, text: MODE_LABEL[leg.mode] || "Bus" })];
    if (leg.risk) tags.push(el("span", { class: "tag risk", text: "⚠ Infrequent" }));

    const when = leg.manual
      ? "Time depends on the event"
      : leg.depart + " → " + leg.arrive + " · " + leg.ride_min + " min" + (leg.stops ? ", " + leg.stops + (leg.stops === 1 ? " stop" : " stops") : "");

    const route = el("dl", { class: "leg-route" }, [
      el("dt", { text: "When" }), el("dd", { class: "when", text: when }),
      el("dt", { text: "Board" }), stopNode(leg.board),
      el("dt", { text: "Alight" }), stopNode(leg.alight),
      item.nextWalk != null ? el("dt", { text: "Then" }) : null,
      item.nextWalk != null ? el("dd", { text: walkText(item.nextWalk) + (item.nextLine ? " to the " + item.nextLine : " to the finish") }) : null,
    ]);

    return el("li", { class: classes, id: "leg-" + id, "data-id": id, style: "--block:" + item.color }, [
      el("input", {
        type: "checkbox",
        class: "check",
        checked: done,
        "aria-label": "Rode " + leg.line,
        onchange: (e) => toggleDone(id, e.target.checked),
      }),
      el("div", { class: "leg-body" }, [
        el("div", { class: "leg-head" }, [
          el("p", { class: "leg-line" }, [el("span", { class: "leg-num", text: n }), el("span", { text: leg.line })].concat(tags)),
          el("button", { type: "button", class: "map-btn", title: "Show on map", "aria-label": "Show " + leg.line + " on map", text: "📍", onclick: () => showOnMap(id) }),
        ]),
        route,
        item.longWalk ? el("p", { class: "warn-line", text: "⚠ ~" + item.walk + " m walk from the previous line — over the 5-block limit." }) : null,
        leg.wait_min >= 12 ? el("p", { class: "leg-note", text: "Scheduled wait here: ~" + leg.wait_min + " min." }) : null,
        leg.note ? el("p", { class: "leg-note", text: leg.note }) : null,
      ]),
    ]);
  }

  function render() {
    renderOptions();

    const blocks = visibleBlocks();
    const items = [];
    blocks.forEach((b) => b.legs.forEach((leg) => {
      const id = legId(leg);
      const prev = items[items.length - 1];
      // The overnight Owl block is separate from the day, so no walk between them.
      const sameSegment = prev && (prev.block === "owl") === (b.id === "owl");
      const walk = sameSegment ? meters(prev.b, leg.board.ll) : null;
      items.push({
        leg, id, block: b.id, color: b.color, done: !!state.done[id], n: items.length + 1,
        a: leg.board.ll, b: leg.alight.ll, path: leg.path,
        walk, longWalk: walk != null && walk > WALK_MAX_M,
      });
    }));
    items.forEach((it, i) => {
      const nx = items[i + 1];
      if (nx && nx.walk != null) { it.nextWalk = nx.walk; it.nextLine = nx.leg.line; }
      else if (!nx || nx.block === "owl" || it.block === "owl") {
        if (it.block !== "owl") { it.nextWalk = meters(it.b, DATA.finish.at); it.nextLine = null; }
      }
    });
    const byId = Object.fromEntries(items.map((i) => [i.id, i]));
    const total = new Set(items.map((i) => i.id)).size;
    const doneCount = items.filter((i) => i.done).length;
    const next = items.find((i) => !i.done);

    const container = $("itinerary");
    container.replaceChildren();
    for (const block of blocks) {
      const blockDone = block.legs.filter((l) => state.done[legId(l)]).length;
      container.append(
        el("section", { id: "block-" + block.id }, [
          el("h2", { class: "block-head", style: "--block:" + block.color }, [
            el("span", {}, [el("span", { class: "time", text: block.time }), block.title]),
            el("span", { class: "count", text: blockDone + "/" + block.legs.length }),
          ]),
          el("ol", { class: "legs" }, block.legs.map((leg) => renderLeg(byId[legId(leg)]))),
        ])
      );
    }

    if (next) $("leg-" + next.id).classList.add("next");
    $("jumpNext").hidden = !next;

    $("doneCount").textContent = doneCount;
    $("totalCount").textContent = total;
    $("progressFill").style.width = (total ? (100 * doneCount) / total : 0) + "%";
    const bar = $("progressBar");
    bar.setAttribute("aria-valuemax", total);
    bar.setAttribute("aria-valuenow", doneCount);

    $("finishText").textContent =
      doneCount === total
        ? "You did it — all " + total + " lines. 🎉"
        : "Planned arrival ~" + PLAN.finishAt + " · " + total + " lines · " + (total - doneCount) + " to go.";

    renderPlanCheck(items);
    MAP.update(items, next && next.id, DATA.finish, blocks);
  }

  function renderPlanCheck(items) {
    const day = items.filter((i) => i.block !== "owl" && !i.leg.manual);
    const walks = items.filter((i) => i.walk != null);
    const longest = walks.reduce((m, i) => Math.max(m, i.walk), 0);
    const long = items.filter((i) => i.longWalk);
    const box = $("planCheck");
    box.className = "card " + (long.length ? "warn-card" : "ok-card");
    box.replaceChildren(
      el("h2", { class: "card-title", text: long.length ? "⚠ Plan check" : "✓ Plan check" }),
      el("ul", {}, [
        el("li", { text: "Built from SFMTA’s weekday timetable: first ride " + (day[0] ? day[0].leg.depart : "—") + ", at Bus Stop by ~" + PLAN.finishAt + "." }),
        el("li", { text: "Every ride is at least ~3 blocks; longest walk between lines ~" + longest + " m." }),
        long.length ? el("li", { text: long.length + " walk(s) over the 5-block limit — see the flagged legs." }) : null,
        PLAN.missing && PLAN.missing.length ? el("li", { text: "Not in SFMTA’s schedule data (approximate): " + PLAN.missing.join(", ") + "." }) : null,
      ]),
      el("p", { class: "muted", text: "Scheduled times assume everything runs on time — there’s little slack, so expect to adapt." })
    );
  }

  function renderStatic() {
    $("excluded").replaceChildren(...DATA.excluded.map((t) => el("li", { text: t })));
    $("caveats").replaceChildren(...DATA.caveats.map((t) => el("li", { text: t })));
  }

  // ---- Wiring ------------------------------------------------------------

  $("jumpNext").addEventListener("click", () => {
    const next = document.querySelector(".leg.next");
    if (!next) return;
    if (document.body.dataset.view === "map" && !WIDE.matches) MAP.focus(next.dataset.id);
    else next.scrollIntoView({ behavior: "smooth", block: "center" });
  });

  document.querySelectorAll(".view-toggle button").forEach((b) => {
    b.addEventListener("click", () => setView(b.dataset.view));
  });
  WIDE.addEventListener("change", () => MAP.resize());

  $("resetBtn").addEventListener("click", () => {
    if (!confirm("Clear all checked-off lines?")) return;
    state.done = {};
    saveState();
    render();
  });

  MAP.init($("map"), { onToggle: (id) => toggleDone(id) });
  renderStatic();
  render();

  // Offline support — only works when served over http(s).
  if ("serviceWorker" in navigator && location.protocol.startsWith("http")) {
    navigator.serviceWorker.register("sw.js").catch(() => {});
  }
})();
