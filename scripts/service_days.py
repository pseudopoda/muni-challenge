#!/usr/bin/env python3
"""
Write js/service-days.js: which dates the plan's weekday timetable does NOT apply to.

Usage:
    python scripts/service_days.py gtfs/muni_gtfs-current.zip

The app warns on weekends, on holidays (Saturday/Sunday schedule), on reduced
holiday-week weekdays, and outside the feed's date range.
"""
import csv
import io
import json
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "js" / "service-days.js"
WEEKDAY = "M11"  # keep in step with plan.py


def rows(z, name):
    if name not in z.namelist():
        return []
    return list(csv.DictReader(io.TextIOWrapper(z.open(name), encoding="utf-8-sig")))


def main(path):
    z = zipfile.ZipFile(path)
    cal = {r["service_id"]: r for r in rows(z, "calendar.txt")}
    if WEEKDAY not in cal:
        sys.exit(f"service {WEEKDAY} not in calendar.txt — update WEEKDAY here and in plan.py")
    kind = {}  # service_id -> what a rider would call it
    for sid, r in cal.items():
        if r["saturday"] == "1" and r["monday"] == "0":
            kind[sid] = "Saturday"
        elif r["sunday"] == "1" and r["monday"] == "0":
            kind[sid] = "Sunday"
    removed, added = set(), {}
    for r in rows(z, "calendar_dates.txt"):
        if r["service_id"] == WEEKDAY and r["exception_type"] == "2":
            removed.add(r["date"])
        elif r["exception_type"] == "1":
            added.setdefault(r["date"], r["service_id"])
    days = {}
    for d in sorted(removed):
        sid = added.get(d)
        days[d] = kind.get(sid, "reduced holiday-week")
    out = {"start": cal[WEEKDAY]["start_date"], "end": cal[WEEKDAY]["end_date"], "days": days}
    OUT.write_text(
        "// Generated by scripts/service_days.py from SFMTA GTFS — do not edit by hand.\n"
        "// Data provided by SFMTA under the SFMTA Transit Data License Agreement.\n"
        "// Dates when the weekday timetable used by the plan does not run.\n"
        "window.MUNI_SERVICE_DAYS = " + json.dumps(out, separators=(",", ":")) + ";\n",
        encoding="utf-8", newline="\n")
    print(f"Wrote {OUT.relative_to(ROOT)}: {len(days)} special dates, {out['start']}–{out['end']}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else str(ROOT / "gtfs" / "muni_gtfs-current.zip"))
