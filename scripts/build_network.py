#!/usr/bin/env python3
"""
Write js/network.js: the full route of every line in js/data.js, from SFMTA's GTFS feed.

Usage:
    python scripts/build_network.py path/to/muni_gtfs-current.zip

For each line it keeps the most-run weekday (or, for Owl lines, any) shape in each
direction, simplified to ~6 m so the file stays small. The map draws these faintly
under the planned route so you can see each whole line, not just the part you ride.
"""
import csv
import io
import json
import math
import sys
import zipfile
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from plan import read_lines, route_short, WEEKDAY  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "js" / "network.js"
TOLERANCE_M = 6


def rows(z, name):
    with z.open(name) as f:
        yield from csv.DictReader(io.TextIOWrapper(f, "utf-8-sig"))


def simplify(pts, tol):
    """Douglas-Peucker on (lat, lon) using a local metric projection."""
    if len(pts) < 3:
        return pts
    lat0 = math.radians(pts[0][0])
    xy = [(p[1] * 111320 * math.cos(lat0), p[0] * 110540) for p in pts]
    keep = [False] * len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        (ax, ay), (bx, by) = xy[a], xy[b]
        dx, dy = bx - ax, by - ay
        L = math.hypot(dx, dy) or 1e-9
        best, bi = 0, None
        for i in range(a + 1, b):
            d = abs(dy * (xy[i][0] - ax) - dx * (xy[i][1] - ay)) / L
            if d > best:
                best, bi = d, i
        if bi is not None and best > tol:
            keep[bi] = True
            stack += [(a, bi), (bi, b)]
    return [p for p, k in zip(pts, keep) if k]


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    z = zipfile.ZipFile(sys.argv[1])
    lines = [name for name, _ in read_lines()]
    routes = {r["route_short_name"]: r["route_id"] for r in rows(z, "routes.txt")}
    want = {routes[route_short(n)]: n for n in lines if route_short(n) in routes}

    counts = defaultdict(Counter)  # (route, direction) -> shape -> weekday trips
    any_shape = defaultdict(Counter)
    for t in rows(z, "trips.txt"):
        if t["route_id"] in want:
            key = (t["route_id"], t["direction_id"])
            any_shape[key][t["shape_id"]] += 1
            if t["service_id"] == WEEKDAY:
                counts[key][t["shape_id"]] += 1
    chosen = {key: (counts.get(key) or any_shape[key]).most_common(1)[0][0] for key in any_shape}

    shapes = defaultdict(list)
    wanted = set(chosen.values())
    for p in rows(z, "shapes.txt"):
        if p["shape_id"] in wanted:
            shapes[p["shape_id"]].append((int(p["shape_pt_sequence"]), float(p["shape_pt_lat"]), float(p["shape_pt_lon"])))

    out = {}
    for (rid, _), sid in sorted(chosen.items()):
        pts = [(lat, lon) for _, lat, lon in sorted(shapes[sid])]
        pts = simplify(pts, TOLERANCE_M)
        out.setdefault(want[rid], []).append([[round(lat, 5), round(lon, 5)] for lat, lon in pts])

    missing = [n for n in lines if n not in out]
    body = json.dumps(out, separators=(",", ":"), ensure_ascii=False)
    OUT.write_text(
        "// Generated by scripts/build_network.py from SFMTA GTFS — do not edit by hand.\n"
        "// Full route shape(s) per line, [[lat, lon], ...], one per direction.\n"
        f"window.MUNI_NETWORK = {body};\n",
        encoding="utf-8",
    )
    print(f"Wrote {OUT} ({OUT.stat().st_size // 1024} KB, {len(out)} lines). Not in feed: {missing}")


if __name__ == "__main__":
    main()
